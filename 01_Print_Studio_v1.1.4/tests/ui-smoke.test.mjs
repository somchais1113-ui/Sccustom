import test from 'node:test';
import assert from 'node:assert/strict';

test('initial UI renders and text-editor step is interactive with event bindings',async()=>{
  const listeners={};const app={innerHTML:'',addEventListener(type,callback){listeners[type]=callback;}};
  const storage=new Map();
  let focused='', scrolled='', opened=false;
  const resolvePanel={tagName:'DETAILS',set open(v){opened=v;},querySelector:()=>({focus(){focused='studio-profile';}}),scrollIntoView(){scrolled='studio-profile';}};
  globalThis.document={baseURI:'https://example.github.io/sccustom/',querySelector:(sel)=>sel==='#app'?app:sel==='#review-heading'?{focus(){focused='review-heading';}}:null,querySelectorAll:()=>[],getElementById:id=>id==='studio-profile'?resolvePanel:null};
  globalThis.localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
  globalThis.window={};
  await import('../app.js');
  assert.match(app.innerHTML,/SCCUSTOM/);
  assert.match(app.innerHTML,/Quantum/);
  assert.match(app.innerHTML,/Colour Variants/);
  assert.match(app.innerHTML,/<select id="template-brand"[^>]+data-brand="1"/);
  assert.match(app.innerHTML,/<option value="elfen" disabled>/);
  assert.match(app.innerHTML,/<option value="" disabled selected>เลือกแบรนด์/);
  assert.doesNotMatch(app.innerHTML,/name="brand"|role="radiogroup"/);
  assert.match(app.innerHTML,/data-action="proof" disabled/);
  assert.doesNotMatch(app.innerHTML,/trigger-brand|brand-file/);
  const click=async(action,dataset={})=>{
    const btn={dataset:{action,...dataset}};await listeners.click({preventDefault(){},target:{closest(){return btn;}}});
  };
  await click('goto-step',{step:'3'});
  assert.match(app.innerHTML,/class="studio-shell"/);
  assert.match(app.innerHTML,/aria-current="step"/);
  assert.match(app.innerHTML,/data-action="studio-view" data-value="product" aria-pressed="true"/);
  assert.doesNotMatch(app.innerHTML,/id="artboard-image"/);
  const key='sccustom-artwork-studio-v1';
  const beforeView=storage.get(key);
  await click('studio-view',{value:'area'});
  assert.match(app.innerHTML,/id="artboard-image"/);
  assert.match(app.innerHTML,/data-drag-area/);
  assert.equal(storage.get(key),beforeView);
  await click('studio-view',{value:'product'});
  assert.doesNotMatch(app.innerHTML,/id="artboard-image"/);
  await click('studio-variant',{variant:'mint'});
  assert.equal(JSON.parse(storage.get(key)).jobs[0].selectedVariant,'mint');
  assert.match(app.innerHTML,/data-variant="mint"[^>]*aria-pressed="true"/);
  const beforeRoute=storage.get(key);
  await click('studio-resolve',{target:'studio-profile'});
  assert.equal(opened,true);
  assert.equal(focused,'studio-profile');
  assert.equal(scrolled,'studio-profile');
  assert.equal(storage.get(key),beforeRoute);
  await click('studio-resolve',{target:'variants'});
  assert.match(app.innerHTML,/Colour Variants/);
  await click('goto-step',{step:'3'});
  assert.match(app.innerHTML,/จัดแบบพิมพ์/);
  assert.match(app.innerHTML,/id="logo-file"/);
  await click('artwork-mode',{value:'text'});
  assert.match(app.innerHTML,/data-text-value/);
  assert.match(app.innerHTML,/แปลงข้อความเป็นเส้นเวกเตอร์/);
  await click('artwork-mode',{value:'both'});
  assert.match(app.innerHTML,/id="logo-file"/);
  assert.match(app.innerHTML,/data-part-gap/);
  assert.match(app.innerHTML,/data-text-side/);
  assert.match(app.innerHTML,/data-tracking/);
  assert.match(app.innerHTML,/data-action="download-design-review"/);
  const input=(selector,value)=>listeners.input({target:{matches:q=>q===selector,value}});
  const change=(selector,value)=>listeners.change({target:{matches:q=>q===selector,value}});
  input('[data-text-value]','แบบทดสอบ เก่า');
  await change('[data-tracking]','12');
  assert.match(app.innerHTML,/data-tracking value="12"/);
  assert.equal(JSON.parse(storage.get('sccustom-artwork-studio-v1')).jobs[0].textArtwork.trackingEm,.12);
  await click('artwork-mode',{value:'logo'});
  assert.doesNotMatch(app.innerHTML,/data-tracking/);
  await click('artwork-mode',{value:'both'});
  assert.match(app.innerHTML,/แบบทดสอบ เก่า/);
  await click('studio-review');
  assert.equal(focused,'review-heading');
  assert.match(app.innerHTML,/id="review-heading"/);
  assert.doesNotMatch(app.innerHTML,/class="studio-shell"/);
  await click('goto-step',{step:'3'});
  assert.match(app.innerHTML,/แบบทดสอบ เก่า/);
  await click('go-view',{view:'library'});
  assert.match(app.innerHTML,/Product Master/);
  assert.match(app.innerHTML,/Master Art/);
  assert.match(app.innerHTML,/Add New Product|เพิ่ม Product Master/);
  await click('go-view',{view:'dashboard'});
  assert.match(app.innerHTML,/Google Drive Workspace/);
  assert.match(app.innerHTML,/Import Project JSON/);
});
